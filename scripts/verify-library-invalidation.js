const assert = require('assert')
const fs = require('fs')
const path = require('path')
const { requestJson, claimDevice, removeTempRootWithRetry } = require('./verify-helpers')
const root = path.resolve(__dirname, '..')
const parent = path.join(root, '.tmp/refactor-tests')
fs.mkdirSync(parent, { recursive: true })
const fixture = fs.mkdtempSync(path.join(parent, 'library-invalidation-'))
process.chdir(fixture)
const settings = require(path.join(root, 'main/settings'))
const scanner = require(path.join(root, 'main/scanner'))
const { createRemoteServer } = require(path.join(root, 'main/remote/server'))
const { createMediaMutationService, savePlaybackRecord } = require(path.join(root, 'main/application/media-mutations'))
const { getLibraryDiagnostics } = require(path.join(root, 'main/remote/handlers/library'))
const identity = require(path.join(root, 'main/remote/identity'))
let server
async function main() {
  const directory = path.join(fixture, 'library')
  fs.mkdirSync(directory)
  const file = path.join(directory, 'sample.mp4')
  fs.writeFileSync(file, 'library-cache-fixture')
  await settings.saveSettingsAndFlush({ directories: [directory], defaultDirectory: directory })
  const item = (await scanner.scanWithCache(directory, true)).videos[0]
  server = createRemoteServer({ port: 0 })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const endpoint = `http://127.0.0.1:${server.address().port}`
  const device = await claimDevice({ baseUrl: endpoint, clientId: 'invalidation-phone', ...identity })
  const headers = { Authorization: 'Bearer ' + device.token }
  let response = await requestJson(endpoint + '/v1/library', { headers })
  assert.strictEqual(response.status, 200)
  const initial = getLibraryDiagnostics()
  for (let i = 0; i < 5; i++) await savePlaybackRecord(file, { position: i * 10, volume: 0 })
  await settings.saveSettingsAndFlush({ theme: 'light' })
  assert.strictEqual(getLibraryDiagnostics().revision, initial.revision, 'progress/theme events must not invalidate the library')
  response = await requestJson(endpoint + '/v1/library', { headers })
  assert.strictEqual(getLibraryDiagnostics().builds, initial.builds, 'control updates must reuse the valid snapshot')
  const service = createMediaMutationService()
  await service.setFavorite(item, true)
  assert.ok(getLibraryDiagnostics().revision > initial.revision)
  response = await requestJson(endpoint + '/v1/library', { headers })
  assert.strictEqual(response.data.items[0].favorite, true)
  await service.setVideoTags(item, ['updated'])
  response = await requestJson(endpoint + '/v1/library', { headers })
  assert.deepStrictEqual(response.data.items[0].customTags, ['updated'])
  assert.strictEqual(response.data.items[0].customTagsRevision, 1)
  await settings.saveSettingsAndFlush({ hiddenTags: ['custom:updated'] })
  response = await requestJson(endpoint + '/v1/library', { headers })
  assert.strictEqual(response.data.items.length, 0)
  console.log('library invalidation passed: progress/theme reuse the live snapshot; favorites/tags/visibility invalidate and expose current data')
}
main().catch(error => { console.error(error); process.exitCode = 1 }).finally(async () => {
  if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)) }
  await scanner.waitForBackgroundScanRefreshes()
  scanner.unwatchAllDirectories()
  await settings.flushSettingsWrites()
  process.chdir(root)
  assert.strictEqual(path.dirname(path.resolve(fixture)), parent)
  assert.ok(path.basename(fixture).startsWith('library-invalidation-'))
  await removeTempRootWithRetry(fixture)
})
