const assert = require('assert')
const { phone } = require('./mobile-module-harness')
const client = phone()
const { ControllerStore, shallowEqual } = client.load('src/services/controller-store.js')
const { shareJson } = client.load('src/utils/share-json.js')
const original = { favorites: [], tags: { first: ['标签'], second: ['保留'] }, profile: { nested: { enabled: true } } }
const copy = value => JSON.parse(JSON.stringify(value))
assert.strictEqual(shareJson(original, copy(original)), original)
const changed = shareJson(original, { ...copy(original), tags: { first: ['新标签'], second: ['保留'] } })
assert.notStrictEqual(changed, original)
assert.strictEqual(changed.favorites, original.favorites)
assert.strictEqual(changed.tags.second, original.tags.second)
assert.strictEqual(changed.profile, original.profile)
assert.strictEqual(shareJson(original, null), null)
assert.deepStrictEqual(JSON.parse(JSON.stringify(shareJson([1, 2], [1]))), [1])
assert.strictEqual(shallowEqual([1], { 0: 1 }), false)
assert.strictEqual(shallowEqual(new Set([1]), new Set([2])), false)
assert.strictEqual(shallowEqual({ value: original }, { value: original }), true)
let notifications = 0
const store = new ControllerStore({ counter: 1, directory: 'before', act: value => ['before', value] })
const snapshot = store.getSnapshot(), action = store.actions.act
const unsubscribe = store.subscribe(() => notifications++)
store.publish({ counter: 1, directory: 'before', act: value => ['latest', value] })
assert.strictEqual(store.getSnapshot(), snapshot)
assert.strictEqual(notifications, 0, 'changing only a callback implementation does not notify state consumers')
assert.deepStrictEqual(action('argument'), ['latest', 'argument'], 'stable actions dispatch the current implementation and preserve the result')
store.publish({ counter: 2, directory: 'after', act: value => ['after', value] })
assert.strictEqual(store.getSnapshot().counter, 2)
assert.strictEqual(store.getSnapshot().act, action)
assert.strictEqual(notifications, 1)
unsubscribe(); store.publish({ counter: 3, act: value => value })
assert.strictEqual(notifications, 1)
assert.strictEqual(store.listeners.size, 0)
const large = Object.fromEntries(Array.from({ length: 10000 }, (_, index) => [String(index), ['标签 ' + index]]))
assert.strictEqual(shareJson(large, copy(large)), large)
console.log('controller store passed: JSON branch sharing, changed values/removals, 10k records, stable snapshots/actions, latest implementation dispatch, selective equality and unsubscribe')
